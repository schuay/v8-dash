def gerrit_time(dt):
    return dt.strftime("%Y-%m-%d %H:%M:%S.000000000")


def ago(**kw):
    return gerrit_time(NOW - timedelta(**kw))


# Gerrit ChangeInfo ---------------------------------------------------------


def change(
    num,
    subject,
    *,
    owner=OWNER,
    status="NEW",
    wip=False,
    ps=1,
    updated=None,
    unresolved=0,
    total=0,
    cr=(),
    cq=(),
    reviewers=(),
    unsatisfied=(),
    messages=(),
    reviewer_updates=(),
):
    """A ChangeInfo as /changes/ returns it with all options the watcher
    asks for; the fake server drops messages unless o=MESSAGES."""

    def label(votes):
        return {"all": [{**acct, "value": v} for acct, v in votes]}

    reqs = [{"name": n, "status": "UNSATISFIED"} for n in unsatisfied]
    reqs.append({"name": "Verified", "status": "SATISFIED"})
    return {
        "_number": num,
        "project": "example/project",
        "subject": subject,
        "owner": owner,
        "status": status,
        "work_in_progress": wip,
        "updated": updated or ago(days=1),
        "current_revision_number": ps,
        "unresolved_comment_count": unresolved,
        "total_comment_count": total,
        "labels": {"Code-Review": label(cr), "Commit-Queue": label(cq)},
        "reviewers": {"REVIEWER": list(reviewers)},
        "submit_requirements": reqs,
        "messages": list(messages),
        "reviewer_updates": list(reviewer_updates),
    }


_msg_ids = iter(range(1, 10**6))


def message(author, text, *, ps=1, tag=None, date=None):
    m = {
        "id": f"m{next(_msg_ids)}",
        "author": author,
        "date": date or ago(hours=1),
        "message": f"Patch Set {ps}:\n\n{text}",
        "_revision_number": ps,
    }
    if tag:
        m["tag"] = tag
    return m


def cv_passed(ps, date=None):
    return message(
        CV,
        "This CL has passed the run",
        ps=ps,
        date=date,
        tag="autogenerated:cq:dry-run:1700000001",
    )


def cv_failed(ps, date=None):
    return message(
        CV,
        "This CL has failed the run. Reason:\n\nTryjob example_linux_rel has failed",
        ps=ps,
        date=date,
        tag="autogenerated:cq:dry-run:1700000002",
    )


