"""Watcher: tracking, state and event logic against a fake Gerrit."""

import json
import unittest

from shepherd import watch
from tests import fixtures as fx
from tests.fake_gerrit import FakeGerrit
from tests.util import ScratchCase


class WatchTest(ScratchCase):
    def setUp(self):
        super().setUp()
        self.g = FakeGerrit()
        self.addCleanup(self.g.close)
        self.configure(self.g.url, gerrit={"extra_cls": [200001]})
        # The owner's open CLs.
        self.g.add(
            fx.change(
                100001, "[parser] Cache scope lookups", ps=2, reviewers=[fx.ALICE]
            )
        )
        self.g.add(fx.change(100002, "[heap] Reuse buckets", wip=True))
        # Owned by someone else; tracked through extra_cls.
        self.g.add(
            fx.change(
                200001, "[api] A colleague's change", owner=BOB, reviewers=[fx.OWNER]
            )
        )

    def poll(self):
        return watch.poll(self.cfg)

    def state(self):
        return json.loads(self.cfg.state.read_text())

    def touch(self, num, **kw):
        """Updates a change on the fake Gerrit and bumps `updated`."""
        c = self.g.changes[num]
        c.update(kw)
        self._touches = getattr(self, "_touches", 0) + 1
        c["updated"] = fx.ago(minutes=60 - self._touches)
        return c

    def test_baseline_then_quiet(self):
        events, rows, missing = self.poll()
        self.assertEqual(events, [])
        self.assertEqual(sorted(n for n, _ in rows), [100001, 100002, 200001])
        self.assertEqual(missing, [])
        st = self.state()
        self.assertTrue(st["100001"]["auto"])
        self.assertNotIn("auto", st["200001"])
        self.assertEqual(st["100001"]["reviewers"], ["alice"])

        mtime = self.cfg.state.stat().st_mtime_ns
        self.assertEqual(self.poll(), ([], None, []))
        # An unchanged poll leaves the state file alone.
        self.assertEqual(self.cfg.state.stat().st_mtime_ns, mtime)

    def test_review_events(self):
        self.poll()
        c = self.g.changes[100001]
        c["messages"] = [
            fx.message(fx.ALICE, "Please add a test.", ps=2),
            fx.message(fx.OWNER, "Done", ps=2),
        ]
        self.touch(
            100001,
            unresolved_comment_count=1,
            total_comment_count=1,
            labels={
                "Code-Review": {"all": [{**fx.ALICE, "value": 1}]},
                "Commit-Queue": {"all": []},
            },
        )
        events, _, _ = self.poll()
        url = f"{self.g.url}/c/example/project/+/100001"
        self.assertEqual(
            events,
            [
                (
                    f"100001 Code-Review+1 by alice (approved) | "
                    f"[parser] Cache scope lookups | {url}"
                ),
                (
                    f"100001 message from alice: Please add a test. | "
                    f"[parser] Cache scope lookups | {url}"
                ),
                (
                    f"100001 comments now 1 total, 1 unresolved | "
                    f"[parser] Cache scope lookups | {url}"
                ),
            ],
        )
        self.assertEqual(self.state()["100001"]["cr_votes"], {"alice": 1})
        # The same messages are not reported twice.
        self.touch(100001)
        self.assertEqual(self.poll()[0], [])

    def test_cv_results(self):
        self.poll()
        c = self.g.changes[100001]
        c["messages"] = [
            fx.message(
                CV,
                "Dry run: CV is trying the patch.",
                ps=2,
                tag="autogenerated:cq:dry-run",
            ),
            fx.cv_failed(2),
        ]
        self.touch(100001)
        events, _, _ = self.poll()
        self.assertEqual(len(events), 1)
        self.assertTrue(
            events[0].startswith(
                "100001 dry-run FAILED (PS2): Tryjob example_linux_rel has failed |"
            ),
            events,
        )
        self.assertEqual(self.state()["100001"]["last_cv"], "dry-run FAILED PS2")

        c["messages"].append(fx.cv_passed(2))
        self.touch(100001)
        events, _, _ = self.poll()
        self.assertEqual(
            [e.split(" | ")[0] for e in events], ["100001 dry-run PASSED (PS2)"]
        )
        self.assertEqual(self.state()["100001"]["last_cv"], "dry-run PASSED PS2")

    def test_owner_and_bot_activity_is_quiet(self):
        self.poll()
        c = self.g.changes[100002]
        c["messages"] = [
            fx.message(
                fx.OWNER,
                "Uploaded patch set 2.",
                ps=2,
                tag="autogenerated:gerrit:newPatchSet",
            ),
            fx.message(
                fx.OWNER,
                "Set Ready For Review",
                ps=2,
                tag="autogenerated:gerrit:setReadyForReview",
            ),
            fx.message(fx.CI_BOT, "Build started", ps=2),
        ]
        self.touch(100002, current_revision_number=2, work_in_progress=False)
        self.assertEqual(self.poll()[0], [])

    def test_foreign_patchset_and_reviewer(self):
        self.poll()
        c = self.g.changes[100001]
        c["messages"] = [
            fx.message(
                BOB,
                "Uploaded patch set 3.",
                ps=3,
                tag="autogenerated:gerrit:newPatchSet",
            )
        ]
        c["reviewer_updates"] = [
            {"state": "REVIEWER", "reviewer": BOB, "updated_by": fx.ALICE}
        ]
        self.touch(
            100001, current_revision_number=3, reviewers={"REVIEWER": [fx.ALICE, BOB]}
        )
        events = [e.split(" | ")[0] for e in self.poll()[0]]
        self.assertEqual(
            events, ["100001 reviewer added: bob", "100001 PS3 uploaded by bob"]
        )

    def test_auto_tracking(self):
        self.poll()
        self.g.add(fx.change(100003, "[wasm] New change"))
        events = self.poll()[0]
        self.assertEqual(
            events,
            [
                (
                    f"100003 new CL tracked | [wasm] New change | "
                    f"{self.g.url}/c/example/project/+/100003"
                )
            ],
        )
        self.assertTrue(self.state()["100003"]["auto"])

        # Closing an auto-tracked CL is reported, then it is no longer polled.
        self.touch(100003, status="MERGED")
        self.assertEqual([e.split(" | ")[0] for e in self.poll()[0]], ["100003 merged"])
        self.g.queries.clear()
        self.poll()
        batched = [q for q in self.g.queries if q.startswith("change:")]
        self.assertNotIn("change:100003", " ".join(batched))
        self.assertIn("100003", self.state())

    def test_missing_cl(self):
        self.configure(self.g.url, gerrit={"extra_cls": [200001, 999999]})
        _, _, missing = self.poll()
        self.assertEqual(missing, [999999])

    def test_bots(self):
        self.assertTrue(watch.is_bot(CV))
        self.assertTrue(watch.is_bot(fx.CI_BOT))
        self.assertTrue(watch.is_bot({"email": "x-bot@example.com"}))
        self.assertFalse(watch.is_bot(fx.ALICE))

    def test_cli_once_and_lock(self):
        out = self.shepherd("watch", "--once")
        self.assertEqual(out.returncode, 0, out.stderr)
        self.assertIn("100001", out.stdout)  # baseline table
        held = watch.lock(self.cfg)
        self.addCleanup(held.close)
        out = self.shepherd("watch", "--once")
        self.assertEqual(out.returncode, 2)
        self.assertIn("another instance holds", out.stderr)


BOB = fx.BOB
CV = fx.CV

if __name__ == "__main__":
    unittest.main()
