"""Watch the tracked CLs on Gerrit and report updates from others.

Read-only and anonymous. One batched /changes/ query per poll; a second
batched query with messages only for CLs whose `updated` timestamp moved.

  shepherd watch --once                    poll once, print events
  shepherd watch [--interval S]            poll in a loop, notify on events
  shepherd watch --exit-on-event           exit after the first eventful poll

Tracked CLs: the owner's open CLs in the project, the configured extra CLs,
--cl arguments, and every CL already in the state file except auto-tracked
ones that have closed. A CL found only through the owner query is marked
`auto` in the state and reported once as `new CL tracked`.

The first run (no state file) records a baseline and prints a summary
table. Only one watcher or waiter runs at a time; a second one exits with
status 2.
"""

import argparse
import fcntl
import json
import os
import shutil
import subprocess
import sys
import time
import urllib.parse
from datetime import datetime

from . import config, gerrit

# Keeps the query URL well below common length limits and under n=100.
CHUNK = 60

OPTS = ["LABELS", "DETAILED_LABELS", "DETAILED_ACCOUNTS", "SUBMIT_REQUIREMENTS"]
MSG_OPTS = [*OPTS, "MESSAGES", "REVIEWER_UPDATES"]

requests_made = 0


def query(cfg, cls, options):
    global requests_made
    out = []
    for i in range(0, len(cls), CHUNK):
        chunk = cls[i : i + CHUNK]
        q = "+OR+".join(f"change:{c}" for c in chunk)
        opts = "".join(f"&o={o}" for o in options)
        requests_made += 1
        out += gerrit.get(f"{cfg.gerrit}/changes/?q={q}{opts}&n={len(chunk) + 10}")
    return out


def owner_open_cls(cfg):
    global requests_made
    q = urllib.parse.quote(
        f"owner:{cfg.require_owner()} status:open project:{cfg.project}"
    )
    requests_made += 1
    return [c["_number"] for c in gerrit.get(f"{cfg.gerrit}/changes/?q={q}&n=500")]


# Accounts and messages -----------------------------------------------------


def is_bot(account):
    email = account.get("email", "")
    local = email.partition("@")[0]
    return (
        "SERVICE_USER" in account.get("tags", ())
        or email.endswith(".gserviceaccount.com")
        or "-bot@" in email
        or local.endswith("bot")
    )


def who(account):
    email = account.get("email")
    if email:
        return email.split("@")[0]
    return account.get("name") or f"#{account.get('_account_id')}"


def votes(change, label, owner_id):
    """{who: value} for non-zero human votes by accounts other than the owner."""
    out = {}
    for v in change.get("labels", {}).get(label, {}).get("all", []):
        if v.get("value") and v.get("_account_id") != owner_id and not is_bot(v):
            out[who(v)] = v["value"]
    return out


def reviewers(change, owner_id):
    return sorted(
        who(a)
        for a in change.get("reviewers", {}).get("REVIEWER", [])
        if a.get("_account_id") != owner_id and not is_bot(a)
    )


def cv_result(msg):
    """(mode, verdict, body) for a LUCI CV result message, else None.

    CV start messages and result messages share the author and the
    `autogenerated:cq:<mode>` tag prefix; results carry a run id suffix
    (`autogenerated:cq:dry-run:1795171249`) and no "is trying the patch".
    The verdict itself is only available as message text.
    """
    tag = msg.get("tag") or ""
    if not (tag.startswith(("autogenerated:cq:", "autogenerated:cv:"))):
        return None
    if not is_bot(msg.get("author", {})):
        return None  # The owner's -Commit-Queue echo, performed by CV.
    body = strip_ps(msg.get("message", ""))
    if "is trying the patch" in body:
        return None
    mode = tag.split(":")[2]
    if body.startswith("This CL has passed the run"):
        verdict = "PASSED"
    elif body.startswith("This CL has failed the run"):
        verdict = "FAILED"
    else:
        verdict = "FAILED (not started)"
    return mode, verdict, body


def strip_ps(text):
    """Drops the leading "Patch Set N:" line Gerrit prepends to messages."""
    if text.startswith("Patch Set "):
        first, _, rest = text.partition("\n")
        head = first.split(":", 1)[1].strip() if ":" in first else ""
        text = (head + "\n" + rest).strip() if head else rest.strip()
    return text


def one_line(text, limit=200):
    s = " ".join(text.split())
    return s if len(s) <= limit else s[: limit - 3] + "..."


def last_cv(messages):
    """The last run that produced a verdict, as "<mode> <verdict> PS<n>".

    A run CV refused to start (eg for an unsatisfied submit requirement) says
    nothing about the patch; snapshot() records the requirement instead.
    """
    for m in reversed(messages):
        r = cv_result(m)
        if r and r[1] in ("PASSED", "FAILED"):
            return f"{r[0]} {r[1]} PS{m.get('_revision_number')}"
    return None


def new_messages(messages, st):
    last = st.get("last_msg_id")
    ids = [m["id"] for m in messages]
    if last in ids:
        return messages[ids.index(last) + 1 :]
    since = st.get("last_msg_date") or st.get("updated") or ""
    return [m for m in messages if m["date"] > since]


# State ---------------------------------------------------------------------


def snapshot(change):
    owner_id = change["owner"]["_account_id"]
    return {
        "subject": change["subject"],
        "owner": who(change["owner"]),
        "updated": change["updated"],
        "status": change["status"],
        "work_in_progress": bool(change.get("work_in_progress")),
        "current_revision_number": change.get("current_revision_number"),
        "unresolved_comment_count": change.get("unresolved_comment_count", 0),
        "total_comment_count": change.get("total_comment_count", 0),
        "cr_votes": votes(change, "Code-Review", owner_id),
        "cq_votes": votes(change, "Commit-Queue", owner_id),
        "reviewers": reviewers(change, owner_id),
        "unsatisfied": sorted(
            r["name"]
            for r in change.get("submit_requirements", [])
            if r["status"] == "UNSATISFIED"
        ),
    }


def load_state(path):
    try:
        with open(path) as f:
            return {int(k): v for k, v in json.load(f).items()}
    except FileNotFoundError:
        return None


def save_state(path, state):
    """Writes the state; leaves the file alone when nothing changed."""
    text = json.dumps({str(k): v for k, v in sorted(state.items())}, indent=1)
    try:
        with open(path) as f:
            if f.read() == text:
                return
    except FileNotFoundError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = f"{path}.tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)


def record_messages(snap, messages):
    if messages:
        snap["last_msg_id"] = messages[-1]["id"]
        snap["last_msg_date"] = messages[-1]["date"]
        snap["last_cv"] = last_cv(messages)


# Events --------------------------------------------------------------------


def diff(cfg, num, old, new, change, msgs):
    """Event strings for one CL whose `updated` moved."""
    ev = []
    owner_id = change["owner"]["_account_id"]

    def by_owner(m):
        return m.get("author", {}).get("_account_id") == owner_id

    owner_active = any(by_owner(m) for m in msgs)
    humans = [m for m in msgs if not by_owner(m) and not is_bot(m.get("author", {}))]

    if new["status"] != old.get("status") and new["status"] in ("MERGED", "ABANDONED"):
        ev.append(new["status"].lower())

    for m in msgs:
        r = cv_result(m)
        if r:
            mode, verdict, body = r
            line = f"{mode} {verdict} (PS{m.get('_revision_number')})"
            if verdict != "PASSED":
                line += ": " + one_line(body.partition("\n")[2] or body, 160)
            ev.append(line)

    for name, val in sorted(new["cr_votes"].items()):
        if old.get("cr_votes", {}).get(name) != val:
            verb = "approved" if val > 0 else "rejected"
            ev.append(f"Code-Review{val:+d} by {name} ({verb})")
    for name, val in sorted(new["cq_votes"].items()):
        if old.get("cq_votes", {}).get(name) != val:
            ev.append(f"Commit-Queue{val:+d} by {name}")

    # Autogenerated messages by humans (code-owners reviewer suggestions,
    # patchset uploads) are covered by the reviewer and patchset checks.
    for m in humans:
        if (m.get("tag") or "").startswith("autogenerated:"):
            continue
        text = one_line(strip_ps(m.get("message", "")))
        ev.append(f"message from {who(m['author'])}: {text}")
    d_total = new["total_comment_count"] - old.get("total_comment_count", 0)
    d_unres = new["unresolved_comment_count"] - old.get("unresolved_comment_count", 0)
    if (d_total > 0 or d_unres > 0) and not humans and not owner_active:
        ev.append(
            f"comments: total {old.get('total_comment_count', 0)}->"
            f"{new['total_comment_count']}, unresolved "
            f"{old.get('unresolved_comment_count', 0)}->"
            f"{new['unresolved_comment_count']}"
        )
    elif humans and (d_total or d_unres):
        ev.append(
            f"comments now {new['total_comment_count']} total, "
            f"{new['unresolved_comment_count']} unresolved"
        )

    added = sorted(set(new["reviewers"]) - set(old.get("reviewers", [])))
    if added:
        by = {
            who(u["reviewer"]): u.get("updated_by", {})
            for u in change.get("reviewer_updates", [])
            if u.get("state") == "REVIEWER"
        }
        others = [r for r in added if by.get(r, {}).get("_account_id") != owner_id]
        if others:
            ev.append("reviewer added: " + ", ".join(others))

    if new["work_in_progress"] != old.get("work_in_progress"):
        wip_tags = (
            "autogenerated:gerrit:setWorkInProgress",
            "autogenerated:gerrit:setReadyForReview",
            "autogenerated:gerrit:newWipPatchSet",
        )
        if any(m.get("tag") in wip_tags for m in humans) or not owner_active:
            ev.append("WIP set" if new["work_in_progress"] else "ready for review")

    if (new["current_revision_number"] or 0) > (
        old.get("current_revision_number") or 0
    ) and new["status"] != "MERGED":
        uploads = [
            m
            for m in msgs
            if (m.get("tag") or "").startswith(
                (
                    "autogenerated:gerrit:newPatchSet",
                    "autogenerated:gerrit:newWipPatchSet",
                )
            )
        ]
        foreign = [m for m in uploads if not by_owner(m)]
        if foreign:
            names = sorted({who(m["author"]) for m in foreign})
            ev.append(
                f"PS{new['current_revision_number']} uploaded by {', '.join(names)}"
            )
        elif not uploads and not owner_active:
            ev.append(f"PS{new['current_revision_number']} uploaded")

    url = cfg.change_url(num)
    subj = one_line(new["subject"], 70)
    return [f"{num} {e} | {subj} | {url}" for e in ev]


def tracked(cfg, state, extra=()):
    """The listed CLs: configured, from the command line, or in the state
    without being auto-tracked."""
    cls = list(cfg.extra_cls) + list(extra)
    cls += [n for n, st in (state or {}).items() if not st.get("auto")]
    seen = set()
    return [c for c in cls if not (c in seen or seen.add(c))]


def poll(cfg, extra=()):
    """Returns (events, summary_rows or None, missing). Raises on network
    errors."""
    state = load_state(cfg.state)
    baseline = state is None
    state = state or {}

    cls = tracked(cfg, state, extra)
    listed = set(cls)
    # Auto-tracked CLs stay until they close, so that merges are reported.
    auto = [n for n in owner_open_cls(cfg) if n not in listed]
    auto += [
        n
        for n, st in state.items()
        if st.get("auto")
        and st["status"] == "NEW"
        and n not in listed
        and n not in auto
    ]
    cls += auto
    changes = {c["_number"]: c for c in query(cfg, cls, OPTS)}

    fresh = [n for n in cls if n in changes and n not in state]
    moved = [
        n
        for n in cls
        if n in changes
        and n in state
        and changes[n]["updated"] != state[n].get("updated")
    ]
    # Entries written before a field was added are rebuilt without events.
    outdated = [
        n
        for n in cls
        if n in changes
        and n in state
        and n not in moved
        and "unsatisfied" not in state[n]
    ]

    detail = {}
    if fresh or moved or outdated:
        detail = {
            c["_number"]: c for c in query(cfg, fresh + moved + outdated, MSG_OPTS)
        }

    events = []
    for n in fresh:
        snap = snapshot(changes[n])
        record_messages(snap, detail.get(n, {}).get("messages", []))
        if n in auto:
            snap["auto"] = True
            if not baseline:
                subj = one_line(snap["subject"], 70)
                events.append(f"{n} new CL tracked | {subj} | {cfg.change_url(n)}")
        state[n] = snap
    for n in moved + outdated:
        change = detail.get(n, changes[n])
        old, new = state[n], snapshot(change)
        msgs = change.get("messages", [])
        if n in moved:
            events += diff(cfg, n, old, new, change, new_messages(msgs, old))
        new["last_cv"] = old.get("last_cv")
        new["last_msg_id"] = old.get("last_msg_id")
        new["last_msg_date"] = old.get("last_msg_date")
        if old.get("auto"):
            new["auto"] = True
        record_messages(new, msgs)
        state[n] = new
    save_state(cfg.state, state)

    missing = [n for n in cls if n not in changes]
    rows = None
    if baseline or fresh:
        rows = [(n, state[n]) for n in (cls if baseline else fresh) if n in state]
    return events, rows, missing


def lock(cfg):
    """Takes the watcher lock; returns the open lock file, or None if another
    process holds it. The lock is released when the process exits."""
    os.makedirs(cfg.watch_dir, exist_ok=True)
    # Append mode: opening must not truncate the file or touch its mtime.
    f = open(f"{cfg.state}.lock", "a")  # noqa: SIM115 held until exit
    try:
        fcntl.flock(f, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        print(f"another instance holds {f.name}", file=sys.stderr)
        f.close()
        return None
    return f


def print_table(rows):
    print(
        f"{'CL':<8} {'state':<9} {'PS':>3} {'unres':>5} {'CR':<22} {'last CV':<20} subject"
    )
    for n, s in rows:
        st = "WIP" if s["work_in_progress"] and s["status"] == "NEW" else s["status"]
        cr = ",".join(f"{k}{v:+d}" for k, v in s["cr_votes"].items()) or "-"
        print(
            f"{n:<8} {st:<9} {s['current_revision_number'] or '-':>3} "
            f"{s['unresolved_comment_count']:>5} {cr:<22} {s.get('last_cv') or '-':<20} "
            f"{one_line(s['subject'], 60)}"
        )


def notify(events):
    """A desktop notification, where the platform has a command for it."""
    title = f"CL watch: {len(events)} update(s)"
    body = one_line("; ".join(e.split(" | ")[0] for e in events), 240)
    if shutil.which("osascript"):
        cmd = [
            "osascript",
            "-e",
            "on run argv",
            "-e",
            "display notification (item 1 of argv) with title (item 2 of argv)",
            "-e",
            "end run",
            body,
            title,
        ]
    elif shutil.which("notify-send"):
        cmd = ["notify-send", title, body]
    else:
        return
    subprocess.run(cmd, check=True)


def log(path, lines):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    with open(path, "a") as f:
        f.writelines(f"{stamp} {line}\n" for line in lines)


def main(argv=None):
    ap = argparse.ArgumentParser(
        prog="shepherd watch",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument("--once", action="store_true")
    ap.add_argument("--interval", type=int)
    ap.add_argument("--exit-on-event", action="store_true")
    ap.add_argument("--cl", type=int, action="append", default=[])
    ap.add_argument("--no-notify", action="store_true")
    ap.add_argument("--debug", action="store_true", help="report request counts")
    args = ap.parse_args(argv)
    cfg = config.load()
    cfg.require_owner()
    interval = args.interval or cfg.interval

    lock_file = lock(cfg)
    if lock_file is None:
        return 2

    while True:
        before = requests_made
        try:
            events, rows, missing = poll(cfg, args.cl)
        except (OSError, ValueError) as e:
            msg = f"poll failed: {e!r}"
            print(msg, file=sys.stderr)
            log(cfg.log, [msg])
            if args.once:
                return 1
            time.sleep(interval)
            continue
        if args.debug:
            print(f"[debug] {requests_made - before} request(s)", file=sys.stderr)
        if missing:
            print(
                f"not found on Gerrit: {' '.join(map(str, missing))}", file=sys.stderr
            )
        if rows:
            print_table(rows)
        for e in events:
            print(e)
        sys.stdout.flush()
        if events and not args.once:
            log(cfg.log, events)
            if cfg.notify and not args.no_notify:
                try:
                    notify(events)
                except (OSError, subprocess.CalledProcessError) as e:
                    print(f"notification failed: {e!r}", file=sys.stderr)
            if args.exit_on_event:
                return 0
        if args.once:
            return 0
        time.sleep(interval)
