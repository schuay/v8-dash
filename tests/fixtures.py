def write_demo(root, with_extras=True):
    """Writes a state directory with every data file. Returns its path."""
    from shepherd.dash import curation

    root = Path(root)
    state_dir = root / "state"
    state_dir.mkdir(parents=True, exist_ok=True)
    state = demo_state()
    curation.write_json(state_dir / "cl-watch-state.json", state)
    curation.write_json(state_dir / "cls.json", demo_cls(state))
    if with_extras:
        curation.write_json(state_dir / "experiments.json", demo_experiments())
        curation.write_json(state_dir / "pinpoint.json", demo_pinpoint())
    (state_dir / "cl-watch.log").write_text(
        "2026-01-15 11:00:00 100001 message from alice: Please add a test "
        "| [parser] Cache scope lookups | "
        "https://gerrit.example.com/c/example/project/+/100001\n"
    )
    (state_dir / "requests.jsonl").touch()
    return state_dir


def write_config(path, state_dir, **sections):
    """A config.toml; `sections` maps section name to {key: value}."""
    data = {
        "gerrit": {
            "host": "https://gerrit.example.com",
            "project": "example/project",
            "owner": "you@example.com",
        },
        "paths": {"state_dir": str(Path(state_dir).resolve())},
    }
    for k, v in sections.items():
        data.setdefault(k, {}).update(v)
    lines = []
    for section, values in data.items():
        lines.append(f"[{section}]")
        lines += [f"{k} = {json.dumps(v)}" for k, v in values.items()]
        lines.append("")
    Path(path).write_text("\n".join(lines))
    return Path(path)


